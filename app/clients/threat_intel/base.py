"""TrustLens AI - Threat Intelligence Base Interface

Standardized evidence representations, status taxonomy, and provider interfaces.
"""

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, Optional
from pydantic import BaseModel, Field


class ProviderStatus(str, Enum):
    OK = "ok"
    NO_MATCH = "no_match"
    CONFIRMED_MATCH = "confirmed_match"
    RATE_LIMITED = "rate_limited"
    UNAUTHORIZED = "unauthorized"
    UNAVAILABLE = "unavailable"
    NOT_CONFIGURED = "not_configured"
    INVALID_REQUEST = "invalid_request"
    ERROR = "error"


class NormalizedEvidenceRecord(BaseModel):
    """Auditable evidence record generated by external providers."""

    provider_name: str
    query_type: str  # "url", "domain", "claim", "ip"
    query_target: str
    status: ProviderStatus
    is_malicious: Optional[bool] = None
    is_phishing: Optional[bool] = None
    is_malware: Optional[bool] = None
    threat_description: Optional[str] = None
    confidence_score: Optional[float] = None
    raw_details: Dict[str, Any] = Field(default_factory=dict)
    source_reference: Optional[str] = None
    retrieval_timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    latency_ms: float = 0.0
    error_message: Optional[str] = None
