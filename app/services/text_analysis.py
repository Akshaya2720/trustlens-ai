"""TrustLens AI - Text Analysis Service

Extracts:
1. Direct observable features (URLs, domains, emails, phones, money, crypto, urgency, credentials, extortion)
   with precise character offsets and textual citations.
2. AI-generated interpretations (social engineering, psychological manipulation, impersonation, factual claims)
   via Meta Model API (Muse Spark 1.3), with explicit deterministic fallbacks if unconfigured.
"""

from enum import Enum
import re
from typing import Any, Dict, List, Optional
from urllib.parse import urlparse
from pydantic import BaseModel, Field

from app.clients.meta_client import MetaModelClient, meta_client
from app.core.logging import logger
from app.core.security import isolate_untrusted_input
from app.services.content_normalizer import (
    CRYPTO_PATTERN,
    EMAIL_PATTERN,
    EXTORTION_LAW_KEYWORDS,
    MONEY_PATTERN,
    PHONE_PATTERN,
    URGENCY_KEYWORDS,
    URL_PATTERN,
    ContentNormalizer,
)
from app.services.safe_url import SafeURLInspector


class ObservationType(str, Enum):
    URL = "url"
    DOMAIN = "domain"
    EMAIL = "email"
    PHONE = "phone"
    MONETARY_DEMAND = "monetary_demand"
    CRYPTO_ADDRESS = "crypto_address"
    URGENCY_INDICATOR = "urgency_indicator"
    CREDENTIAL_REQUEST = "credential_request"
    EXTORTION_THREAT = "extortion_threat"
    IMPERSONATION_CANDIDATE = "impersonation_candidate"


class DirectObservation(BaseModel):
    """Direct, verifiable textual observation directly extracted from submitted content."""
    observation_type: ObservationType
    extracted_value: str
    quote: str
    char_start: int
    char_end: int
    context: str


class AIInterpretation(BaseModel):
    """Subjective or cognitive reasoning generated by Meta AI."""
    category: str
    assessment: str
    cited_phrases: List[str] = Field(default_factory=list)
    confidence: float = 0.5


class PotentialImpersonation(BaseModel):
    claimed_organization: Optional[str] = None
    sender_domain_or_address: Optional[str] = None
    is_domain_mismatch: bool = False
    evidence_citation: Optional[str] = None


class TextAnalysisResult(BaseModel):
    """Unified text analysis payload separating direct observations from AI reasoning."""
    # Direct Observations (Zero AI extrapolation)
    direct_observations: List[DirectObservation] = Field(default_factory=list)
    extracted_urls: List[str] = Field(default_factory=list)
    extracted_domains: List[str] = Field(default_factory=list)
    extracted_emails: List[str] = Field(default_factory=list)
    extracted_phones: List[str] = Field(default_factory=list)
    
    # Feature Flags based on direct observations
    has_urgency: bool = False
    has_credential_harvesting: bool = False
    has_financial_demands: bool = False
    has_extortion_threats: bool = False
    
    # Cognitive / AI Interpretations
    ai_available: bool = False
    ai_interpretations: List[AIInterpretation] = Field(default_factory=list)
    potential_impersonation: Optional[PotentialImpersonation] = None
    claims_for_verification: List[str] = Field(default_factory=list)
    
    # Summary & Limitations
    observable_summary: str
    limitations: List[str] = Field(default_factory=list)


# Credential and OTP harvesting patterns
CREDENTIAL_PATTERNS = [
    re.compile(r"\b(?:otp|one[- ]time password|verification code|security code)\b", re.IGNORECASE),
    re.compile(r"\b(?:password|passcode|pin|login credentials|login details)\b", re.IGNORECASE),
    re.compile(r"\b(?:social security|ssn|seed phrase|private key)\b", re.IGNORECASE),
]

KNOWN_ORGANIZATIONS = [
    ("bank of america", "bankofamerica.com"),
    ("chase", "chase.com"),
    ("wells fargo", "wellsfargo.com"),
    ("citi", "citi.com"),
    ("paypal", "paypal.com"),
    ("apple", "apple.com"),
    ("google", "google.com"),
    ("microsoft", "microsoft.com"),
    ("amazon", "amazon.com"),
    ("irs", "irs.gov"),
    ("netflix", "netflix.com"),
    ("usps", "usps.com"),
    ("fedex", "fedex.com"),
    ("ups", "ups.com"),
]


class TextAnalysisService:
    """Production service for deep textual analysis and entity/indicator extraction."""

    @classmethod
    def extract_direct_observations(cls, text: str) -> List[DirectObservation]:
        """Harvests observable entities and phrase matches strictly with character offsets."""
        observations: List[DirectObservation] = []

        def add_obs(obs_type: ObservationType, val: str, start: int, end: int):
            ctx_start = max(0, start - 25)
            ctx_end = min(len(text), end + 25)
            observations.append(
                DirectObservation(
                    observation_type=obs_type,
                    extracted_value=val,
                    quote=text[start:end],
                    char_start=start,
                    char_end=end,
                    context=text[ctx_start:ctx_end],
                )
            )

        # 1. URLs & Domains
        for match in URL_PATTERN.finditer(text):
            raw_url = match.group(0).rstrip(".,;:!?)")
            norm_url = SafeURLInspector.normalize_url(raw_url)
            start, end = match.start(), match.start() + len(raw_url)
            add_obs(ObservationType.URL, norm_url, start, end)

            parsed = urlparse(norm_url)
            if parsed.netloc:
                add_obs(ObservationType.DOMAIN, parsed.netloc.lower(), start, end)

        # 2. Emails
        for match in EMAIL_PATTERN.finditer(text):
            email = match.group(0).lower()
            add_obs(ObservationType.EMAIL, email, match.start(), match.end())

        # 3. Phones
        for match in PHONE_PATTERN.finditer(text):
            phone = match.group(0).strip()
            add_obs(ObservationType.PHONE, phone, match.start(), match.end())

        # 4. Monetary Demands
        for match in MONEY_PATTERN.finditer(text):
            money = match.group(0).strip()
            add_obs(ObservationType.MONETARY_DEMAND, money, match.start(), match.end())

        # 5. Crypto Addresses
        for match in CRYPTO_PATTERN.finditer(text):
            addr = match.group(0).strip()
            add_obs(ObservationType.CRYPTO_ADDRESS, addr, match.start(), match.end())

        # 6. Urgency Keywords
        text_lower = text.lower()
        for kw in URGENCY_KEYWORDS:
            for m in re.finditer(re.escape(kw), text_lower):
                add_obs(ObservationType.URGENCY_INDICATOR, kw, m.start(), m.end())

        # 7. Credential / OTP Requests
        for pat in CREDENTIAL_PATTERNS:
            for m in pat.finditer(text):
                add_obs(ObservationType.CREDENTIAL_REQUEST, m.group(0), m.start(), m.end())

        # 8. Extortion / Law Enforcement Threats
        for kw in EXTORTION_LAW_KEYWORDS:
            for m in re.finditer(re.escape(kw), text_lower):
                add_obs(ObservationType.EXTORTION_THREAT, kw, m.start(), m.end())

        # 9. Known Brand Mentions
        for brand_name, official_domain in KNOWN_ORGANIZATIONS:
            for m in re.finditer(r"\b" + re.escape(brand_name) + r"\b", text_lower):
                add_obs(ObservationType.IMPERSONATION_CANDIDATE, brand_name.title(), m.start(), m.end())

        return observations

    @classmethod
    async def analyze_text(
        cls,
        text: str,
        sender_hint: Optional[str] = None,
        client: Optional[MetaModelClient] = None,
    ) -> TextAnalysisResult:
        """Executes full text analysis pipeline combining observable facts and AI reasoning."""
        client = client or meta_client
        observations = cls.extract_direct_observations(text)

        # Collect unique lists
        urls = list(dict.fromkeys([o.extracted_value for o in observations if o.observation_type == ObservationType.URL]))
        domains = list(dict.fromkeys([o.extracted_value for o in observations if o.observation_type == ObservationType.DOMAIN]))
        emails = list(dict.fromkeys([o.extracted_value for o in observations if o.observation_type == ObservationType.EMAIL]))
        phones = list(dict.fromkeys([o.extracted_value for o in observations if o.observation_type == ObservationType.PHONE]))

        has_urgency = any(o.observation_type == ObservationType.URGENCY_INDICATOR for o in observations)
        has_credentials = any(o.observation_type == ObservationType.CREDENTIAL_REQUEST for o in observations)
        has_money = any(o.observation_type in (ObservationType.MONETARY_DEMAND, ObservationType.CRYPTO_ADDRESS) for o in observations)
        has_extortion = any(o.observation_type == ObservationType.EXTORTION_THREAT for o in observations)

        # Detect potential impersonation from direct evidence
        potential_impersonation: Optional[PotentialImpersonation] = None
        brand_obs = [o for o in observations if o.observation_type == ObservationType.IMPERSONATION_CANDIDATE]
        if brand_obs or sender_hint:
            claimed = brand_obs[0].extracted_value if brand_obs else sender_hint
            matched_official = None
            if claimed:
                for b_name, b_domain in KNOWN_ORGANIZATIONS:
                    if b_name.lower() in claimed.lower():
                        matched_official = b_domain
                        break

            mismatch = False
            if matched_official and domains:
                mismatch = all(matched_official not in d for d in domains)

            potential_impersonation = PotentialImpersonation(
                claimed_organization=claimed,
                sender_domain_or_address=sender_hint or (domains[0] if domains else None),
                is_domain_mismatch=mismatch,
                evidence_citation=f"Observed claimed organization '{claimed}' with destination domain(s): {domains}" if mismatch else None,
            )

        ai_interpretations: List[AIInterpretation] = []
        claims: List[str] = []
        limitations: List[str] = []
        ai_available = False

        # Attempt Meta AI Reasoning if configured
        if client and client.is_configured:
            try:
                system_prompt = (
                    "You are a cybersecurity expert analyzing suspicious user text for fraud, phishing, and social engineering.\n"
                    "Separately identify:\n"
                    "1. Psychological manipulation tactics (artificial urgency, fear, greed).\n"
                    "2. Factual claims that could be checked against external databases.\n"
                    "3. Any impersonation indicators.\n"
                    "Every finding MUST cite verbatim phrases from the submitted content.\n"
                    "Format output as a valid JSON object with keys: interpretations (list of {category, assessment, cited_phrases, confidence}) and claims (list of str)."
                )

                user_prompt = f"Analyze this content:\n{isolate_untrusted_input(text, 'ANALYSIS_TARGET')}"
                if sender_hint:
                    user_prompt += f"\nClaimed sender: {sender_hint}"

                messages = [
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": user_prompt},
                ]

                chat_resp = await client.generate_reasoning(messages=messages, temperature=0.1)
                ai_available = True

                # Parse JSON content safely
                try:
                    import json
                    cleaned = chat_resp.content.strip()
                    if cleaned.startswith("```"):
                        cleaned = "\n".join(cleaned.splitlines()[1:-1] if cleaned.splitlines()[-1].startswith("```") else cleaned.splitlines()[1:]).strip()
                    parsed_json = json.loads(cleaned)

                    for item in parsed_json.get("interpretations", []):
                        ai_interpretations.append(
                            AIInterpretation(
                                category=item.get("category", "threat_reasoning"),
                                assessment=item.get("assessment", ""),
                                cited_phrases=item.get("cited_phrases", []),
                                confidence=float(item.get("confidence", 0.8)),
                            )
                        )
                    claims = [str(c) for c in parsed_json.get("claims", [])]
                except Exception:
                    ai_interpretations.append(
                        AIInterpretation(
                            category="general_reasoning",
                            assessment=chat_resp.content[:500],
                            confidence=0.7,
                        )
                    )

            except Exception as e:
                logger.warning(f"Meta AI analysis failed or returned error: {e}")
                limitations.append(f"Meta AI inference unavailable ({type(e).__name__}): {str(e)}")
        else:
            limitations.append("Meta Model API is not configured (MODEL_API_KEY). Analysis performed using deterministic rule heuristics.")

        # If AI was not available, provide grounded deterministic interpretations
        if not ai_interpretations:
            if has_urgency:
                urgency_quotes = [o.quote for o in observations if o.observation_type == ObservationType.URGENCY_INDICATOR]
                ai_interpretations.append(
                    AIInterpretation(
                        category="social_engineering",
                        assessment="High-pressure temporal constraint detected designed to induce compliance before critical verification.",
                        cited_phrases=urgency_quotes[:3],
                        confidence=0.85,
                    )
                )
            if has_credentials:
                cred_quotes = [o.quote for o in observations if o.observation_type == ObservationType.CREDENTIAL_REQUEST]
                ai_interpretations.append(
                    AIInterpretation(
                        category="credential_harvesting",
                        assessment="Explicit solicitation of sensitive credentials or one-time authentication codes.",
                        cited_phrases=cred_quotes[:3],
                        confidence=0.95,
                    )
                )
            if has_extortion:
                extort_quotes = [o.quote for o in observations if o.observation_type == ObservationType.EXTORTION_THREAT]
                ai_interpretations.append(
                    AIInterpretation(
                        category="extortion_or_coercion",
                        assessment="Threat of legal action, arrest, or severe consequences to coerce immediate action.",
                        cited_phrases=extort_quotes[:3],
                        confidence=0.90,
                    )
                )

        # Generate observable summary
        summary_parts = []
        if urls:
            summary_parts.append(f"{len(urls)} URL(s) detected: {', '.join(urls[:2])}")
        if has_urgency:
            summary_parts.append("Observable urgency indicators identified")
        if has_credentials:
            summary_parts.append("Credential or OTP harvesting patterns detected")
        if has_money:
            summary_parts.append("Monetary demands or cryptocurrency requests present")
        if potential_impersonation and potential_impersonation.is_domain_mismatch:
            summary_parts.append(f"Impersonation domain mismatch observed for {potential_impersonation.claimed_organization}")

        observable_summary = "; ".join(summary_parts) if summary_parts else "No immediate high-risk observable patterns detected."

        return TextAnalysisResult(
            direct_observations=observations,
            extracted_urls=urls,
            extracted_domains=domains,
            extracted_emails=emails,
            extracted_phones=phones,
            has_urgency=has_urgency,
            has_credential_harvesting=has_credentials,
            has_financial_demands=has_money,
            has_extortion_threats=has_extortion,
            ai_available=ai_available,
            ai_interpretations=ai_interpretations,
            potential_impersonation=potential_impersonation,
            claims_for_verification=claims,
            observable_summary=observable_summary,
            limitations=limitations,
        )
